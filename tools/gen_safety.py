"""Writes lib/core/safety_data.dart from backend/app/safety_data.py so the app's
offline 'Talk to Smriti' recognises emergencies with exactly the same words and
shows exactly the same reply as the server. Run from the repository root:

    python tools/gen_safety.py          # rewrite the file
    python tools/gen_safety.py --check  # exit 1 if it is out of date (CI/tests)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.safety_data import EMERGENCY_REPLY, EMERGENCY_WORDS  # noqa: E402

OUT = ROOT / "lib/core/safety_data.dart"


def q(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def render() -> str:
    out = ["// GENERATED by tools/gen_safety.py from backend/app/safety_data.py. Do not edit.", "",
           "const emergencyWords = {"]
    for code, words in EMERGENCY_WORDS.items():
        out.append(f"  {q(code)}: [{', '.join(q(w) for w in words)}],")
    out += ["};", "", "const emergencyReply = {"]
    for code, text in EMERGENCY_REPLY.items():
        out.append(f"  {q(code)}: {q(text)},")
    out += ["};", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print("wrote", OUT)
