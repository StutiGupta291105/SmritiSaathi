"""Rewrites lib/core/lang/_all.dart from the language files next to it.

    python tools/gen_lang_registry.py
"""
from pathlib import Path

d = Path(__file__).resolve().parents[1] / "lib/core/lang"
codes = sorted(p.stem for p in d.glob("*.dart") if not p.stem.startswith("_"))
lines = ["// GENERATED by tools/gen_lang_registry.py. Do not edit.",
         "import '../lang_data.dart';"]
lines += [f"import '{c}.dart';" for c in codes]
lines += ["", "/// Registry of the language packs, one per language file.",
          "const Map<String, LangData> kAllLangPacks = {"]
lines += [f"  '{c}': kLang{c.capitalize()}," for c in codes]
lines += ["};", ""]
(d / "_all.dart").write_text("\n".join(lines))
print("registered:", " ".join(codes))
